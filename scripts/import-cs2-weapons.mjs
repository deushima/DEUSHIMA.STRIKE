// Public game-data snapshot; no binaries or proprietary game code are imported.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const repository = 'SteamTracking/GameTracking-CS2';
const sourcePath = 'game/csgo/pak01_dir/scripts/weapons.vdata';
async function get(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.text();
}
const commit = JSON.parse(await get(`https://api.github.com/repos/${repository}/commits?path=${sourcePath}&per_page=1`))[0];
const sourceUrl = `https://raw.githubusercontent.com/${repository}/${commit.sha}/${sourcePath}`;
const source = await get(sourceUrl);
const steamInfo = await get(`https://raw.githubusercontent.com/${repository}/${commit.sha}/game/csgo/steam.inf`);
const tokens = source.replace(/<!--[^]*?-->/g, '').replace(/\/\/[^\n]*/g, '').match(/"(?:\\.|[^"\\])*"|[{}\[\]=,:]|[^\s{}\[\]=,:]+/g);
let index = 0;
function value() {
  const t = tokens[index++];
  if (t === '{') {
    const out = {};
    while (tokens[index] !== '}') {
      const key = tokens[index++].replace(/^"|"$/g, '');
      if (tokens[index++] !== '=') throw new Error(`Expected assignment at ${key}`);
      out[key] = value();
      if (tokens[index] === ',') index++;
    }
    index++; return out;
  }
  if (t === '[') {
    const out = [];
    while (tokens[index] !== ']') { out.push(value()); if (tokens[index] === ',') index++; }
    index++; return out;
  }
  if (tokens[index] === ':') { index++; return value(); }
  if (t.startsWith('"')) return JSON.parse(t);
  if (t === 'true' || t === 'false') return t === 'true';
  return Number.isFinite(Number(t)) ? Number(t) : t;
}
const tree = value();
function resolve(id, seen = new Set()) {
  if (seen.has(id) || !tree[id]) throw new Error(`Missing/cyclic base ${id}`);
  seen.add(id);
  const def = tree[id];
  return { ...(def._base ? resolve(def._base, seen) : {}), ...def };
}
const aliases = { ak47:'weapon_ak47', m4a1:'weapon_m4a1', m4a1s:'weapon_m4a1_silencer', glock:'weapon_glock', usp:'weapon_usp_silencer', deagle:'weapon_deagle', mp5:'weapon_mp5sd', awp:'weapon_awp', scout:'weapon_ssg08', m3:'weapon_nova', xm1014:'weapon_xm1014', m249:'weapon_m249' };
const profiles = {};
for (const [id, sourceId] of Object.entries(aliases)) {
  const d = resolve(sourceId);
  const pair = key => Array.isArray(d[key]) ? d[key] : [d[key], d[key]];
  profiles[id] = {
    sourceId, baseDamage:d.m_nDamage, headshotMultiplier:d.m_flHeadshotMultiplier,
    armorRatio:d.m_flArmorRatio, rangeModifier:d.m_flRangeModifier, rangeCS:d.m_flRange,
    penetration:d.m_flPenetration, cycleTime:pair('m_flCycleTime'), magazine:d.m_iMaxClip1,
    reserve:d.m_nPrimaryReserveAmmoMax * (d.m_bReserveAmmoAsClips ? d.m_iMaxClip1 : 1),
    pellets:d.m_nNumBullets, fullAuto:d.m_bIsFullAuto, burst:d.m_bHasBurstMode,
    silencer:d.m_eSilencerType, maxSpeed:pair('m_flMaxSpeed'), zoomLevels:d.m_nZoomLevels,
    zoomFov:[d.m_nZoomFOV1,d.m_nZoomFOV2], reloadLockout:d.m_flDisallowAttackAfterReloadStartDuration,
    deploy:d.m_flDeployDuration, spread:pair('m_flSpread'),
    inaccuracy:Object.fromEntries(['Stand','Crouch','Move','Jump','Land','Fire','Ladder','Reload','JumpInitial','JumpApex'].map(k=>[k.toLowerCase(),d['m_flInaccuracy'+k]])),
    recoil:{seed:d.m_nRecoilSeed,angle:pair('m_flRecoilAngle'),angleVariance:pair('m_flRecoilAngleVariance'),magnitude:pair('m_flRecoilMagnitude'),magnitudeVariance:pair('m_flRecoilMagnitudeVariance')},
    recovery:{stand:d.m_flRecoveryTimeStand,standFinal:d.m_flRecoveryTimeStandFinal,crouch:d.m_flRecoveryTimeCrouch,crouchFinal:d.m_flRecoveryTimeCrouchFinal,start:d.m_nRecoveryTransitionStartBullet,end:d.m_nRecoveryTransitionEndBullet},
  };
}
